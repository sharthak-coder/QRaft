/**
 * Backward-compatible preset lookup resolving both current and legacy IDs
 */
export function getPresetById(id: string): Preset | undefined {
  const directMatch = PRESETS.find((p) => p.id === id);
  if (directMatch) return directMatch;

  // Legacy ID alias map
  const legacyAliases: Record<string, string> = {
    'peacock': 'indigo',
    'saffron-sun': 'haldi-glow',
    'lotus-pond': 'grove',
    'terracotta': 'sindoor',
    'godna-stipple': 'godna',
  };

  const targetId = legacyAliases[id];
  return targetId ? PRESETS.find((p) => p.id === targetId) : undefined;
}
